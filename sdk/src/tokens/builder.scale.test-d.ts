/**
 * Product-side depth guard: a realistic 60-link token builder,
 * followed by system registration and two independently consolidated forks.
 */
import { createSystem } from '@mszr/vanity'
import { describe, expectTypeOf, it } from 'vitest'

describe('token builder depth', () => {
  it('keeps a long additive chain below TS2589', () => {
    const open = createSystem()
    const tokens = open.defineTokens()
      .add('t00', '0px')
      .add('t01', '1px')
      .add('t02', '2px')
      .add('t03', '3px')
      .add('t04', '4px')
      .add('t05', '5px')
      .add('t06', '6px')
      .add('t07', '7px')
      .add('t08', '8px')
      .add('t09', '9px')
      .add('t10', '10px')
      .add('t11', '11px')
      .add('t12', '12px')
      .add('t13', '13px')
      .add('t14', '14px')
      .add('t15', '15px')
      .add('t16', '16px')
      .add('t17', '17px')
      .add('t18', '18px')
      .add('t19', '19px')
      .add('t20', '20px')
      .add('t21', '21px')
      .add('t22', '22px')
      .add('t23', '23px')
      .add('t24', '24px')
      .add('t25', '25px')
      .add('t26', '26px')
      .add('t27', '27px')
      .add('t28', '28px')
      .add('t29', '29px')
      .add('t30', '30px')
      .add('t31', '31px')
      .add('t32', '32px')
      .add('t33', '33px')
      .add('t34', '34px')
      .add('t35', '35px')
      .add('t36', '36px')
      .add('t37', '37px')
      .add('t38', '38px')
      .add('t39', '39px')
      .add('t40', '40px')
      .add('t41', '41px')
      .add('t42', '42px')
      .add('t43', '43px')
      .add('t44', '44px')
      .add('t45', '45px')
      .add('t46', '46px')
      .add('t47', '47px')
      .add('t48', '48px')
      .add('t49', '49px')
      .add('t50', '50px')
      .add('t51', '51px')
      .add('t52', '52px')
      .add('t53', '53px')
      .add('t54', '54px')
      .add('t55', '55px')
      .add('t56', '56px')
      .add('t57', '57px')
      .add('t58', '58px')
      .add('t59', '59px')

    const base = open.addTokens(tokens)
    const first = base.consolidate({ prefix: 'first' })
    const second = base.consolidate({ prefix: 'second' })

    expectTypeOf(first.t.t00.$name).toEqualTypeOf<'--first-t00'>()
    expectTypeOf(first.t.t59.$name).toEqualTypeOf<'--first-t59'>()
    expectTypeOf(second.t.t59.$name).toEqualTypeOf<'--second-t59'>()
  })
})
