/**
 * Generate deterministic small, medium, and large benchmark workspaces from
 * one scale model. Checked-in fixtures make benchmark and type-performance
 * changes reproducible without maintaining three drifting hand-written apps.
 */

import type { BenchmarkScale } from '../benchmarks/scales'
import type { BenchmarkByteFacts, BenchmarkScaleByteFacts } from './benchmark-facts'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { benchmarkScales } from '../benchmarks/scales'
import {
  compareBenchmarkByteFacts,
  countBenchmarkByteFacts,
  formatBenchmarkByteDifferences,
  readBenchmarkByteFacts,
} from './benchmark-facts'

interface BenchmarkOptions {
  readonly check: boolean
  readonly workspaceDir: string
}

function parseOptions(args: readonly string[]): BenchmarkOptions {
  let check = false
  let workspacePath: string | undefined

  for (let index = 0; index < args.length; index++) {
    const argument = args[index]
    if (argument === '--check') {
      check = true
      continue
    }

    if (argument === '--workspace') {
      const value = args[++index]
      if (value === undefined || value.startsWith('--'))
        throw new Error('`--workspace` requires a path')
      workspacePath = value
      continue
    }

    if (argument?.startsWith('--workspace=')) {
      const value = argument.slice('--workspace='.length)
      if (value.length === 0)
        throw new Error('`--workspace` requires a path')
      workspacePath = value
      continue
    }

    throw new Error(`Unknown option ${argument ?? ''}; expected --check or --workspace <path>`)
  }

  return {
    check,
    workspaceDir: workspacePath === undefined
      ? join(fileURLToPath(new URL('.', import.meta.url)), '..')
      : resolve(workspacePath),
  }
}

const { check, workspaceDir } = parseOptions(process.argv.slice(2))
const generatedRoot = join(workspaceDir, 'benchmarks/generated')
const header = '// Generated by scripts/generate-benchmarks.ts. Do not edit by hand.\n\n'

function padded(value: number, width: number): string {
  return String(value).padStart(width, '0')
}

function moduleName(index: number): string {
  return `tokenModule${padded(index, 2)}`
}

function groupName(index: number): string {
  return `group${padded(index, 2)}`
}

function tokenName(index: number): string {
  return `token${padded(index, 4)}`
}

function moduleRanges(scale: BenchmarkScale): Array<{ count: number, start: number }> {
  const base = Math.floor(scale.tokens / scale.modules)
  const remainder = scale.tokens % scale.modules
  let start = 0

  return Array.from({ length: scale.modules }, (_, index) => {
    const count = base + (index < remainder ? 1 : 0)
    const range = { count, start }
    start += count
    return range
  })
}

function tokenModuleSource(moduleIndex: number, start: number, count: number): string {
  const entries = Array.from({ length: count }, (_, offset) => {
    const index = start + offset
    const conditional = offset === 2 && moduleIndex % 10 === 0
    const val = offset === 0
      ? `open.oklch(0.96, 0.01, ${index % 360})`
      : conditional
        ? `open.tdef({ val: open.oklch(0.96, 0.01, ${index % 360}), mutable: true, axes: { scheme: { dark: open.oklch(0.16, 0.01, ${index % 360}) }, density: { compact: open.oklch(0.9, 0.02, ${index % 360}) } }, cases: [{ when: { scheme: 'dark', density: 'compact' }, val: open.oklch(0.22, 0.02, ${index % 360}) }], description: 'Module ${moduleIndex} conditional' })`
        : `'${(index % 64) + 1}px'`
    const renameMarker = moduleIndex === 0 && offset === 0 ? '/* @rename */' : ''
    return `    ${renameMarker}${tokenName(index)}: ${val},`
  }).join('\n')

  return `${header}import { open } from '../design-system'

export const ${moduleName(moduleIndex)} = open.defineTokens({
  ${groupName(moduleIndex)}: {
${entries}
  },
})
`
}

function systemSource(scale: BenchmarkScale): string {
  const imports = Array.from({ length: scale.modules }, (_, index) =>
    `import { ${moduleName(index)} } from './modules/module-${padded(index, 2)}.tokens'`).join('\n')
  const composition = Array.from({ length: scale.modules }, (_, index) =>
    `  .add(${moduleName(index)})`).join('\n')

  return `${header}import { open } from './design-system'
${imports}

const tokens = open.defineTokens()
${composition}

export const ds = open.addTokens(tokens).consolidate({
  prefix: 'bench-${scale.name}',
})
`
}

function showcaseSource(scale: BenchmarkScale, ranges: Array<{ count: number, start: number }>): string {
  const consumers = Array.from({ length: scale.consumers }, (_, index) => {
    const moduleIndex = index % scale.modules
    const range = ranges[moduleIndex]!
    const color = `${groupName(moduleIndex)}.${tokenName(range.start)}`
    const length = `${groupName(moduleIndex)}.${tokenName(range.start + Math.min(1, range.count - 1))}`

    if (index % 3 === 2) {
      return `export const recipe${padded(index, 3)} = ds.recipe({
  base: { background: ds.t.${color}, padding: ds.t.${length} },
  variants: {
    tone: {
      quiet: { opacity: 0.82 },
      strong: { opacity: 1 },
    },
  },
  defaults: { tone: 'quiet' },
})`
    }

    return `export const style${padded(index, 3)} = ds.class({
  background: ds.t.${color},
  padding: ds.t.${length},
})`
  }).join('\n\n')

  return `${header}import { ds } from './system'

${consumers}
`
}

function probeSource(ranges: Array<{ count: number, start: number }>): string {
  const first = ranges[0]!
  const deep = first.start + Math.min(1, first.count - 1)
  const conditional = first.start + Math.min(2, first.count - 1)

  return `${header}import { tokenModule00 } from './modules/module-00.tokens'
import { ds } from './system'

export const rootProbe = ds.t./* @complete-root */${groupName(0)}
export const deepProbe = ds.t.${groupName(0)}./* @complete-deep */${tokenName(deep)}
export const diagnosticProbe = ds.t.${groupName(0)}./* @diagnostic */${tokenName(deep)}
export const cssProbe = ds.class({ /* @complete-css */padding: ds.t.${groupName(0)}.${tokenName(deep)} })
export const axisProbe = ds.t.${groupName(0)}.${tokenName(conditional)}.$axes./* @complete-axis */density
export const caseProbe = ds.t.${groupName(0)}.${tokenName(conditional)}.$case({ /* @complete-case */scheme: 'dark', density: 'compact' })
export const runtimeProbe = ds.runtime().t.${groupName(0)}.${tokenName(conditional)}./* @complete-runtime */$set
export const moduleTokens = ds.tokensOf(tokenModule00)
export const moduleNames = ds.namesOf(tokenModule00)
export const moduleVars = ds.varsOf(tokenModule00)
`
}

function tsconfigSource(scale: BenchmarkScale): string {
  return `${JSON.stringify({
    extends: '../../../tsconfig.base.json',
    compilerOptions: {
      incremental: true,
      tsBuildInfoFile: `../../../.vanity/benchmarks/${scale.name}.tsbuildinfo`,
      noUnusedLocals: false,
      noUnusedParameters: false,
    },
    include: ['src/**/*.ts'],
  }, null, 2)}\n`
}

function declarationConfigSource(scale: BenchmarkScale): string {
  return `${JSON.stringify({
    extends: './tsconfig.json',
    compilerOptions: {
      incremental: false,
      rootDir: './src',
      declaration: true,
      emitDeclarationOnly: true,
      noEmit: false,
      outDir: `../../../.vanity/benchmarks/declarations/${scale.name}`,
    },
  }, null, 2)}\n`
}

function viteConfigSource(): string {
  return `${header}// eslint-disable-next-line antfu/no-import-dist
import { vanityPlugin } from '../../../sdk/dist/vite.mjs'

export default {
  plugins: [vanityPlugin({ compiler: { system: './src/system.ts' } })],
}
`
}

function filesForScale(scale: BenchmarkScale): Map<string, string> {
  const files = new Map<string, string>()
  const ranges = moduleRanges(scale)

  const optionalAxes = [
    scale.axes >= 3 ? '  contrast: { modes: { normal: \'&\', high: data(\'contrast\', \'high\') }, default: \'normal\' },' : undefined,
    scale.axes >= 4 ? '  motion: { modes: { full: \'&\', reduced: data(\'motion\', \'reduced\') }, default: \'full\' },' : undefined,
  ].filter(Boolean).join('\n')
  files.set('src/design-system.ts', `${header}import { colorSchemes, createSystem, data } from '@mszr/vanity'

export const open = createSystem().addAxes({
  scheme: colorSchemes({ locality: 'root' }),
  density: { modes: { comfortable: '&', compact: data('density', 'compact') }, default: 'comfortable' },
${optionalAxes}
})
`)

  for (const [index, range] of ranges.entries()) {
    files.set(`src/modules/module-${padded(index, 2)}.tokens.ts`, tokenModuleSource(index, range.start, range.count))
  }

  files.set('src/system.ts', systemSource(scale))
  files.set('src/showcase.css.ts', showcaseSource(scale, ranges))
  files.set('src/probes.ts', probeSource(ranges))
  files.set('src/main.ts', `${header}import * as showcase from './showcase.css.ts'\n\ndocument.querySelector('#app')!.textContent = String(Object.keys(showcase).length)\n`)
  files.set('index.html', '<main id="app"></main>\n<script type="module" src="/src/main.ts"></script>\n')
  files.set('package.json', `${JSON.stringify({
    name: `vanity-benchmark-${scale.name}`,
    type: 'module',
    private: true,
    dependencies: {
      '@mszr/vanity': 'link:../../../sdk',
    },
  }, null, 2)}\n`)
  files.set('tsconfig.json', tsconfigSource(scale))
  files.set('tsconfig.declarations.json', declarationConfigSource(scale))
  files.set('vite.config.ts', viteConfigSource())
  return files
}

function existingFiles(root: string, current = root): string[] {
  if (!existsSync(current))
    return []

  return readdirSync(current, { withFileTypes: true }).flatMap((entry) => {
    if (['.vanity', 'dist', 'node_modules'].includes(entry.name))
      return []
    const path = join(current, entry.name)
    return entry.isDirectory() ? existingFiles(root, path) : [relative(root, path)]
  }).sort()
}

function parseDocumentedBytes(value: string): number[] {
  return [...value.matchAll(/([\d,]+)\s+B/g)].map(match => Number(match[1]!.replaceAll(',', '')))
}

function parseDocumentedNumber(
  document: string,
  pattern: RegExp,
  field: string,
  failures: string[],
): number | undefined {
  const match = document.match(pattern)
  if (match === null) {
    failures.push(`benchmarks.md is missing ${field}`)
    return undefined
  }
  const value = Number(match[1]!.replaceAll(',', ''))
  if (!Number.isFinite(value)) {
    failures.push(`benchmarks.md ${field} is not a finite byte count`)
    return undefined
  }
  return value
}

function tableRows(document: string, headerText: string): ReadonlyMap<string, readonly string[]> {
  const lines = document.split(/\r?\n/)
  const headerIndex = lines.findIndex(line => line.includes(headerText))
  if (headerIndex < 0)
    return new Map()

  const rows = new Map<string, readonly string[]>()
  for (const line of lines.slice(headerIndex + 1)) {
    if (!line.startsWith('|'))
      break
    if (/^\|\s*-/.test(line))
      continue
    const cells = line.split('|').slice(1, -1).map(cell => cell.trim())
    const name = cells.shift()
    if (name !== undefined && name.length > 0)
      rows.set(name, cells)
  }
  return rows
}

function parseBenchmarkDocumentation(
  document: string,
  scaleNames: readonly string[],
  failures: string[],
): BenchmarkByteFacts | undefined {
  const rootBytes = parseDocumentedNumber(document, /The current package root entry is ([\d,]+) B raw\./, 'the package root entry', failures)
  const runtime = document.match(/The runtime entry is\s+([\d,]+)\s+B\s+raw,\s+([\d,]+)\s+B\s+minified,\s+and\s+([\d,]+)\s+B\s+min\+gzipped\./)
  if (runtime === null)
    failures.push('benchmarks.md is missing the runtime entry measurements')
  const runtimeBytes = runtime === null ? undefined : Number(runtime[1]!.replaceAll(',', ''))
  const runtimeMinifiedBytes = runtime === null ? undefined : Number(runtime[2]!.replaceAll(',', ''))
  const runtimeMinGzipBytes = runtime === null ? undefined : Number(runtime[3]!.replaceAll(',', ''))
  const presetsBytes = parseDocumentedNumber(document, /The Hail presets entry is\s+([\d,]+)\s+B\s+raw,/, 'the Hail presets entry', failures)
  const rows = tableRows(document, 'Declaration emit / bytes')
  const scales: Record<string, BenchmarkScaleByteFacts> = {}

  for (const scaleName of scaleNames) {
    const displayName = scaleName[0]!.toUpperCase() + scaleName.slice(1)
    const cells = rows.get(displayName)
    if (cells === undefined) {
      failures.push(`benchmarks.md is missing the ${displayName} scale byte row`)
      continue
    }
    const declaration = parseDocumentedBytes(cells[0] ?? '')
    const css = parseDocumentedBytes(cells[2] ?? '')
    const manifest = parseDocumentedBytes(cells[3] ?? '')
    if (declaration.length !== 1)
      failures.push(`benchmarks.md ${displayName} declaration row must contain one byte count`)
    if (css.length !== 2)
      failures.push(`benchmarks.md ${displayName} CSS row must contain raw and gzip byte counts`)
    if (manifest.length !== 2)
      failures.push(`benchmarks.md ${displayName} manifest row must contain raw and gzip byte counts`)
    if (declaration.length !== 1 || css.length !== 2 || manifest.length !== 2)
      continue
    scales[scaleName] = {
      declarationsBytes: declaration[0]!,
      cssBytes: css[0]!,
      cssGzipBytes: css[1]!,
      manifestBytes: manifest[0]!,
      manifestGzipBytes: manifest[1]!,
    }
  }

  if ([rootBytes, runtimeBytes, runtimeMinifiedBytes, runtimeMinGzipBytes, presetsBytes].includes(undefined)
    || Object.keys(scales).length !== scaleNames.length) {
    return undefined
  }

  return {
    package: {
      rootBytes: rootBytes!,
      presetsBytes: presetsBytes!,
      runtimeBytes: runtimeBytes!,
      runtimeMinifiedBytes: runtimeMinifiedBytes!,
      runtimeMinGzipBytes: runtimeMinGzipBytes!,
    },
    scales,
  }
}

function verifyBenchmarkDocumentation(): string[] {
  const failures: string[] = []
  const accepted = readBenchmarkByteFacts(join(workspaceDir, 'benchmarks/accepted.json'), failures)
  if (accepted === undefined)
    return failures

  const document = readFileSync(join(workspaceDir, 'docs/maintainers/benchmarks.md'), 'utf8')
  const documented = parseBenchmarkDocumentation(document, Object.keys(accepted.scales), failures)
  if (documented === undefined)
    return failures

  const differences = compareBenchmarkByteFacts(documented, accepted)
  failures.push(...formatBenchmarkByteDifferences(differences, 'documented', 'accepted'))
  if (failures.length === 0)
    console.log(`✓ benchmarks.md: ${countBenchmarkByteFacts(accepted)} byte figures match benchmarks/accepted.json`)
  return failures
}

function verifyScale(scale: BenchmarkScale, files: Map<string, string>): string[] {
  const root = join(generatedRoot, scale.name)
  const failures: string[] = []
  const expected = [...files.keys()].sort()
  const actual = existingFiles(root)

  if (JSON.stringify(actual) !== JSON.stringify(expected))
    failures.push(`${scale.name}: file list differs; run pnpm run bench:generate`)

  for (const [path, source] of files) {
    const target = join(root, path)
    if (!existsSync(target) || readFileSync(target, 'utf8') !== source)
      failures.push(`${scale.name}/${path}: generated content differs`)
  }

  return failures
}

function writeScale(scale: BenchmarkScale, files: Map<string, string>): void {
  const root = join(generatedRoot, scale.name)
  rmSync(root, { recursive: true, force: true })

  for (const [path, source] of files) {
    const target = join(root, path)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, source)
  }
}

const fixtures = benchmarkScales.map(scale => ({ files: filesForScale(scale), scale }))

if (check) {
  const failures = [
    ...fixtures.flatMap(({ files, scale }) => verifyScale(scale, files)),
    ...verifyBenchmarkDocumentation(),
  ]
  if (failures.length > 0) {
    console.error(failures.join('\n'))
    process.exitCode = 1
  }
  else {
    console.log(`✓ ${fixtures.length} generated benchmark fixtures match their source-controlled generator`)
  }
}
else {
  for (const { files, scale } of fixtures)
    writeScale(scale, files)
  console.log(`✓ generated ${fixtures.length} benchmark fixtures in ${relative(workspaceDir, generatedRoot)}`)
}
