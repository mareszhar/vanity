import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'

// Run: pnpm exec tsx scripts/generate-css-grammar.ts [--check]
// Spike A owns platform observations and Webref generation; this projection
// ships their named data without a dependency on a development-only package.
const root = new URL('../', import.meta.url)
const grammar = JSON.parse(await readFile(new URL('spikes/property-grammar-agreement/grammar.generated.json', root), 'utf8'))
const gaps = JSON.parse(await readFile(new URL('spikes/property-grammar-agreement/platform-gaps.json', root), 'utf8'))
const { createLexer } = createRequire(new URL('sdk/package.json', root))('css-tree')
const valueTypes = await readFile(new URL('sdk/src/values/types.ts', root), 'utf8')
const semanticTypes = new Set([...valueTypes.slice(valueTypes.indexOf('export type VanityCssDataType'), valueTypes.indexOf('/** Whether')).matchAll(/'([^']+)'/g)].map(match => match[1]))
const definitions = new Map<string, any[]>()
for (const type of grammar.types)
  definitions.set(type.name, [...definitions.get(type.name) ?? [], type])
const defaultTypes = Object.fromEntries([...definitions].map(([name, entries]) => [name, (entries.find(entry => !entry.for.length) ?? entries[0]).syntax]))
const lexers = new Map<string, any>()
const propertyData = Object.fromEntries(Object.entries(grammar.properties).map(([property, entry]: [string, any]) => {
  const scoped = Object.fromEntries([...definitions].flatMap(([name, entries]) => {
    const scoped = entries.find(type => type.for.includes(property))
    return scoped ? [[name, scoped.syntax]] : []
  }))
  const scopeKey = JSON.stringify(scoped)
  if (!lexers.has(scopeKey))
    lexers.set(scopeKey, createLexer({ properties: Object.fromEntries(Object.entries(grammar.properties).filter(([, entry]: any) => entry.syntax).map(([name, entry]: any) => [name, entry.syntax])), types: { ...defaultTypes, ...scoped }, generic: true }))
  const lexer = lexers.get(scopeKey)
  const references = new Set<string>()
  const slotReferences = new Set<string>()
  const acceptedTypes = new Set<string>()
  const seen = new Set<string>()
  let incomplete = false
  const visit = (kind: string, name: string, semantic = false): void => {
    const key = `${kind}:${name}:${semantic}`
    if (seen.has(key))
      return
    seen.add(key)
    references.add(`${kind}:${name}`)
    if (!semantic)
      slotReferences.add(`${kind}:${name}`)
    if (kind === 'Type' && semanticTypes.has(name)) {
      if (!semantic)
        acceptedTypes.add(name)
      semantic = true
    }
    const syntax = kind === 'Property' ? lexer.getProperty(name, false)?.syntax : lexer.getType(name)?.syntax
    if (!syntax) {
      if (!semantic && !name.endsWith('()'))
        incomplete = true
      return
    }
    const walk = (node: any, semantic: boolean): void => {
      if (node.type === 'Property' || node.type === 'Type')
        visit(node.type, node.name, semantic)
      if (node.type === 'Group') {
        // Function arguments are not values accepted at the enclosing slot.
        const insideFunction = semantic || node.terms.some((term: any) => term.type === 'Function')
        node.terms.forEach((term: any) => walk(term, insideFunction))
      }
      if (node.type === 'Multiplier')
        walk(node.term, semantic)
    }
    walk(syntax, semantic || (kind === 'Type' && name.endsWith('()')))
  }
  visit('Property', property)
  const unresolved = gaps.native[property] ?? gaps.agreement[property]?.reason
  return [property, { acceptedTypes: [...acceptedTypes].sort(), references: [...references].sort(), slotReferences: [...slotReferences].sort(), components: entry.longhands, logicalPropertyGroup: entry.logicalPropertyGroup, incomplete, ...(unresolved ? { unresolved } : {}) }]
}))
// The lexer builds its own syntax trees. Corpus receipts stay in the spike;
// authoring needs only each unresolved family's reason, not its observed cells.
const runtimeGaps = { native: gaps.native, agreement: Object.fromEntries(Object.entries(gaps.agreement).map(([property, entry]: [string, any]) => [property, { reason: entry.reason }])) }
const output = `${JSON.stringify({ source: grammar.source, properties: grammar.properties, propertyData, types: grammar.types, selectors: grammar.selectors, gaps: runtimeGaps }, null, 2)}\n`
const destination = new URL('sdk/src/css/property-grammar.generated.json', root)
const typeDestination = new URL('sdk/src/css/property-types.generated.ts', root)
const cursor = `// Generated by scripts/generate-css-grammar.ts; do not edit.\n// This projection has the same source as runtime component grammar data.\nimport type { VanityCssDataType } from '../values/types'\n\nexport interface VanityPropertyDataTypes {\n${Object.entries(propertyData).map(([name, entry]) => {
  const camel = name.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase())
  return `  ${camel}: ${entry.incomplete || entry.unresolved ? 'VanityCssDataType' : entry.acceptedTypes.map(type => `'${type}'`).join(' | ') || 'never'}`
}).join('\n')}\n}\n`
if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), output, 'Property grammar drift; run scripts/generate-css-grammar.ts')
  assert.equal(await readFile(typeDestination, 'utf8'), cursor, 'Property cursor types drift; run scripts/generate-css-grammar.ts')
}
else {
  await writeFile(destination, output)
  await writeFile(typeDestination, cursor)
}
